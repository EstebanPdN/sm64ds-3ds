"""Built-in star select preload lists from Azahar session logs.

Every level load logs the files it read ("Level files level=N ... ids=a,b,c",
hal/fs.cpp). This merges those lines (first load order, union of loads) into
source/integrated_native/options/level_files_seed.hpp. Usage:

  python3 tools/generate_level_files_seed.py LOG [LOG ...]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'source/integrated_native/options/level_files_seed.hpp'
PER_LEVEL, LEVELS = 160, 64
LINE = re.compile(r'^Level files level=(-?\d+) loaded=\d+ preloaded=\d+ ids=([0-9,]*)$')


def collect(paths):
    lists = {}
    for path in paths:
        for line in Path(path).read_text(errors='replace').splitlines():
            match = LINE.match(line.strip())
            if not match:
                continue
            level = int(match.group(1))
            if not 0 <= level < LEVELS or not match.group(2):
                continue
            ids = lists.setdefault(level, [])
            for value in match.group(2).split(','):
                if int(value) not in ids and len(ids) < PER_LEVEL:
                    ids.append(int(value))
    return lists


def render(lists):
    lines = ['#pragma once',
             '// Built-in star select preload lists (level_files.hpp): files each course read',
             '// while it loaded in Azahar (benchmark sessions, EUR ROM). Generated by',
             '// tools/generate_level_files_seed.py; consoles add what they load themselves.',
             '#include "level_files.hpp"', '', 'namespace level_files {']
    for level, ids in sorted(lists.items()):
        lines.append('inline constexpr uint16_t seed_%d[] = {%s};' % (level, ','.join(map(str, ids))))
    entries = ',\n    '.join('{%d, %d, seed_%d}' % (level, len(ids), level) for level, ids in sorted(lists.items()))
    lines += ['inline constexpr Seed seeds[] = {', '    ' + (entries or '{0, 0, nullptr}'), '};',
              'inline constexpr unsigned seed_count = %d;' % len(lists), '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    lists = collect(sys.argv[1:])
    OUTPUT.write_text(render(lists))
    print('%s: %d levels (%s)' % (OUTPUT.relative_to(ROOT), len(lists),
                                 ', '.join('%d:%d' % (k, len(v)) for k, v in sorted(lists.items()))))
