def original_calls(original, name):
    text, digest, size = proof.disassemble_original(original, name)
    result = []
    lines = text.splitlines()
    for i, line in enumerate(lines):
        match = re.search(r'\b(?:bl|b)\s+0x([0-9a-f]+)\b', line)
        if not match:
            continue
        address = int(match[1], 16)
        names = original.target_names(original.names[name]['module'], address)
        if names:
            result.append(dict(instruction=line.strip(), target_address=hex(address),
                resolved_names=names, context=[l.strip() for l in lines[max(0, i-4):i+5]]))
    return dict(address=hex(original.names[name]['address']), code_sha256=digest,
        bytes=size, resolved_calls=result), text


