#!/usr/bin/env python3
"""Check the ROM-free native renderer lab against an analytic pixel oracle.

No image libraries or game assets. Read the actual completed PICA transfer,
not a CPU preview. Two pixels around authored edges are excluded because
raster edge rounding is outside this rigid/material acceptance fixture.
"""
import argparse
import hashlib
import json
import re
import math
from pathlib import Path


def inspect(path, offset, clear_order=False,uv_tint=False,wrap=None):
    data = path.read_bytes()
    if len(data) != 400 * 240 * 3:
        raise ValueError('Expected exactly 288000 portrait BGR8 bytes: ' + str(path))
    checked = mismatched = 0
    worst = 0
    examples = []
    for y in range(240):
        y_edges = (70,130) if clear_order else (20,60,100,130,210)
        if any(abs(y-edge) <= 2 for edge in y_edges):
            continue
        for x in range(400):
            local_x = x-offset
            x_edges = (80,180) if clear_order else (20,100,180,220,380)
            if any(abs(local_x-edge) <= 2 for edge in x_edges):
                continue
            expected = (24, 32, 40, 255)
            if clear_order:
                expected = (255,0,0,255) if 80 < local_x < 180 and 70 < y < 130 else (48,80,112,255)
            elif 20 < y < 100:
                if 20 < local_x < 180:
                    if wrap:
                        def sample(value):
                            cell=math.floor(value);fraction=value-cell
                            return 1-fraction if wrap=='mirror' and cell%2 else fraction
                        u=sample(3*(local_x-20+.5)/160-1);v=sample(3*(y-20+.5)/80-1)
                        expected=((255,0,0,255) if u<.5 else (0,255,0,255)) if v<.5 else (
                            (0,0,255,255) if u<.5 else (255,255,0,255))
                    elif uv_tint:
                        expected = ((128,255,0,255) if local_x < 100 else (0,0,128,255)) if y < 60 else (
                            (0,255,0,255) if local_x < 100 else (128,0,0,255))
                    else:
                        expected = ((255, 0, 0, 255) if local_x < 100 else (0, 255, 0, 255)) if y < 60 else (
                            (0, 0, 255, 255) if local_x < 100 else (255, 255, 0, 255))
                elif 220 < local_x < 380:
                    expected = (255, 0, 0, 255)
            elif 130 < y < 210:
                if 20 < local_x < 180:
                    expected = (0, 128, 127, 255)
                elif 220 < local_x < 380:
                    expected = (255, 255, 255, 255)
            at = (x*240+239-y)*3
            actual = tuple(reversed(data[at:at+3]))
            expected = expected[:3]
            error = max(abs(a-b) for a, b in zip(actual, expected))
            checked += 1
            worst = max(worst, error)
            if error > 1:
                mismatched += 1
                if len(examples) < 8:
                    examples.append(dict(x=x, y=y, expected=expected, actual=actual))
    checksum=2166136261
    for value in data:
        checksum=((checksum^value)*16777619)&0xffffffff
    log=(path.parent/'log.txt').read_text()
    source_checksums=re.findall(r'^readback='+re.escape(path.stem)+r' fnv1a=([0-9a-f]{8}) ',log,re.M)
    source_matches=len(source_checksums)==1 and int(source_checksums[0],16)==checksum
    return dict(file=path.name, sha256=hashlib.sha256(data).hexdigest(), offset=offset,
                source_checksum_matches=source_matches,
                checked=checked, mismatched=mismatched, worst_channel_error=worst,
                examples=examples, passed=mismatched == 0 and source_matches)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--session', type=Path, required=True)
    args = parser.parse_args()
    sd = args.session / 'user/sdmc/sm64ds'
    results = [inspect(sd / (name + '.bgr'), offset) for name, offset in
               (('mono', 0), ('stereo-left', -3), ('stereo-right', 3))]
    results.append(inspect(sd / 'clear-order.bgr', 0, clear_order=True))
    results.append(inspect(sd / 'uv-tint.bgr',0,uv_tint=True))
    for name in ('repeat','mirror'):results.append(inspect(sd/(name+'.bgr'),0,wrap=name))
    report = dict(scope='Authored rigid geometry, texture orientation, indexed ranges, depth and alpha on emulated/physical PICA',
                  full_game=False, physical_hardware_validated=False,
                  expected_images='Independent analytic rectangle/material oracle; no golden image generated by renderer',
                  tolerance=1, ignored_edge_radius_pixels=2, images=results,
                  passed=all(r['passed'] for r in results))
    (args.session / 'native-image-check.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    return 0 if report['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
