#!/usr/bin/env python3
"""Review-only 320x240 layouts from original sprites. Does not patch runtime."""
from pathlib import Path
import json, hashlib, struct, sys
from PIL import Image, ImageDraw, ImageFont
OUT=Path(__file__).resolve().parent
ROOT=OUT.parents[2]

def camera_header(output):
 """Embed only the two approved PNGs, without cropping, filtering or scaling."""
 layout=json.loads((OUT/'layouts.json').read_text())
 if layout['selected_layout']!='E-original-HUD-integer-arrows':raise ValueError('Camera layout selection changed')
 rows=['#pragma once','// Generated by assets/proposals/lower-hud-2026-10-18/generate.py --camera-header.',
       '// Original Nintendo artwork; sheet credit: Storice / The Spriters Resource.',
       '// Exact PNG RGBA bytes packed as 0xAARRGGBB; native 32x32, no resampling.',
       '#include <cstdint>','namespace native_gameplay_camera::art {']
 for name,x in [('left',10),('right',278)]:
  placement=next(p for p in layout['layouts'][layout['selected_layout']] if p['sprite']==name)
  if placement!={'sprite':name,'x':x,'y':198,'width':32,'height':32}:raise ValueError('Camera layout contract changed')
  path=OUT/'sprites'/f'{name}.png';im=Image.open(path).convert('RGBA')
  if im.size!=(32,32):raise ValueError('Camera source must remain 32x32')
  rows += [f'// {name}.png SHA-256: {hashlib.sha256(path.read_bytes()).hexdigest()}',f'inline constexpr uint32_t {name}[1024]={{']
  pixels=[(a<<24)|(r<<16)|(g<<8)|b for r,g,b,a in im.get_flattened_data()]
  rows += [' '+','.join(f'0x{c:08x}u' for c in pixels[i:i+8])+',' for i in range(0,1024,8)]
  rows += ['};']
 rows += ['}']
 Path(output).write_text('\n'.join(rows)+'\n')

if '--camera-header' in sys.argv:
 if len(sys.argv)!=3 or sys.argv[1]!='--camera-header':raise SystemExit('Usage: generate.py --camera-header OUTPUT')
 camera_header(sys.argv[2]);raise SystemExit(0)

import ndspy.lz10
sheet=Image.open(OUT/'original-hud-sheet.png').convert('RGBA')
BG={(0,127,149),(25,214,247)}
boxes={'yoshi_life':(260,36,280,55),'yoshi_map':(260,76,280,108),
       'star':(190,195,207,213),'coin':(190,0,206,19),'times':(206,0,221,19),
       'left':(260,283,292,315),'right':(294,283,326,315),
       'map_star':(260,207,289,234)}
for n in range(10):boxes[str(n)]=(260+10*n,0,270+10*n,18)
sprites={}
for name,box in boxes.items():
 im=sheet.crop(box);im.putdata([(r,g,b,0 if (r,g,b) in BG else a) for r,g,b,a in im.get_flattened_data()]);bounds=im.getbbox();im=im.crop(bounds)
 sprites[name]=im
 (OUT/'sprites').mkdir(exist_ok=True);im.save(OUT/'sprites'/f'{name}.png')
# Decode the original castle map, without HUD baked into it.
r=ROOT/'third_party/sm64ds-3ds/sm64ds-decomp/extracted/dsd/files/data/stage/main_castle'
def read(n):
 b=(r/n).read_bytes()
 try:return ndspy.lz10.decompress(b)
 except:return b
t=read('main_castle_icg.bin');p=struct.unpack('<256H',read('main_castle_icl.bin'));m=struct.unpack('<256H',read('main_castle_00_isc.bin'))
map_im=Image.new('RGBA',(128,128))
for y in range(128):
 for x in range(128):
  e=m[y//8*16+x//8];u=7-x%8 if e&1024 else x%8;v=7-y%8 if e&2048 else y%8
  c=p[t[(e&1023)*64+v*8+u]];map_im.putpixel((x,y),((c&31)*255//31,(c>>5&31)*255//31,(c>>10&31)*255//31,255))
map_im.save(OUT/'map-reference.png')
placements={}
def render(name,scale,arrowsize,margin):
 im=Image.new('RGBA',(320,240),map_im.getpixel((0,0)))
 im.alpha_composite(map_im.resize((320,320),Image.Resampling.NEAREST),(0,-40))
 records=[]
 def sprite(key,x,y,factor=scale,size=None):
  src=sprites[key];wh=size or (round(src.width*factor),round(src.height*factor));obj=src.resize(wh,Image.Resampling.NEAREST)
  assert 0<=x and 0<=y and x+wh[0]<=320 and y+wh[1]<=240,(key,x,y,wh)
  im.alpha_composite(obj,(x,y));records.append(dict(sprite=key,x=x,y=y,width=wh[0],height=wh[1]));return wh[0]
 def group(keys,x,y):
  hh=max(round(sprites[k].height*scale) for k in keys)
  for k in keys:x+=sprite(k,x,y+(hh-round(sprites[k].height*scale))//2)+2
 def width(keys):return sum(round(sprites[k].width*scale)+2 for k in keys)-2
 life=['yoshi_life','times','4'];stars=['star','times','1','2'];coins=['coin','times','0']
 group(life,margin,margin);group(stars,320-margin-width(stars),margin)
 group(coins,(320-width(coins))//2,margin if scale<2 else 46)
 sprite('left',margin,240-margin-arrowsize,size=(arrowsize,arrowsize))
 sprite('right',320-margin-arrowsize,240-margin-arrowsize,size=(arrowsize,arrowsize))
 # Map markers keep their independent source resolution and map position.
 sprite('yoshi_map',150,147,1);sprite('star',223,94,1)
 im.save(OUT/f'{name}-320x240.png');im.resize((960,720),Image.Resampling.NEAREST).save(OUT/f'{name}-preview.png')
 placements[name]=records
 return im
variants=[('A-original',1,32,10),('B-balanced',1.25,40,10),('C-integer-double',2,32,8)]
imgs=[render(*v) for v in variants]
render('D-approved-A-hud-B-arrows',1,40,10)
render('E-original-HUD-integer-arrows',1,32,10)
comparison=Image.new('RGB',(1000,292),(30,33,39));d=ImageDraw.Draw(comparison)
labels=['A  ORIGINAL 1x','B  ADAPTADO 1.25x','C  ORIGINAL 2x']
for i,(im,label) in enumerate(zip(imgs,labels)):
 x=10+i*330;d.text((x,9),label,fill='white');comparison.paste(im,(x,36))
comparison.resize((2000,584),Image.Resampling.NEAREST).save(OUT/'comparison.png')
(OUT/'layouts.json').write_text(json.dumps({'review_only':True,'selected_layout':'E-original-HUD-integer-arrows','source_url':'https://www.spriters-resource.com/ds_dsi/supermario64ds/asset/137713/','source_sha256':hashlib.sha256((OUT/'original-hud-sheet.png').read_bytes()).hexdigest(),'credit':'Storice / The Spriters Resource; original Nintendo assets','canvas':[320,240],'filter':'nearest; no redrawing','crops':boxes,'layouts':placements},indent=2)+'\n')
